#!/usr/bin/env python3
"""Generate main/font8x16.h (ASCII 0x20..0x7E, 8x16, 1 bit/pixel, MSB = leftmost) from DejaVu Sans Mono."""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
OUT = sys.argv[2] if len(sys.argv) > 2 else "main/font8x16.h"
SIZE, W, H, BASE = 13, 8, 16, 12

font = ImageFont.truetype(TTF, SIZE)
rows = []
for code in range(0x20, 0x7F):
    im = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, BASE), chr(code), font=font, fill=1, anchor="ls")
    px = im.load()
    rows.append([sum((1 << (7 - x)) for x in range(W) if px[x, y]) for y in range(H)])

with open(OUT, "w") as f:
    f.write("// Generated by tools/gen_font.py - do not edit.\n#pragma once\n#include <stdint.h>\n")
    f.write("#define FONT_W 8\n#define FONT_H 16\n#define FONT_FIRST 0x20\n#define FONT_LAST 0x7E\n")
    f.write("static const uint8_t font8x16[][16] = {\n")
    for code, r in zip(range(0x20, 0x7F), rows):
        f.write("    {" + ",".join("0x%02X" % b for b in r) + "}, /* '" + (chr(code) if chr(code) not in "\\'" else "\\" + chr(code)) + "' */\n")
    f.write("};\n")
print("wrote", OUT, len(rows), "glyphs")
